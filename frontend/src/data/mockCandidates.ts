export function getCandidateDetail(id: string): CandidateDetail | undefined {
  if (mockCandidateDetails[id]) return mockCandidateDetails[id];
  // Synthesize a detail record from a summary so any candidate is openable.
  const summary = mockCandidates.find((c) => c.id === id);
  if (!summary) return undefined;
  return {
    candidate_id: summary.id,
    name: summary.name,
    position: summary.position,
    grade: summary.grade,
    appliedAt: summary.appliedAt,
    resumeUrl: `https://example.com/resume-${summary.id}.pdf`,
    score: summary.scorePercent / 100,
    score_percent: summary.scorePercent,
    verdict: summary.verdict,
    status: summary.status,
    recommendation:
      summary.verdict === "recommend_to_interview"
        ? "Профиль выглядит перспективно для роли. Стоит провести техническое интервью."
        : "Профиль пока не дотягивает до ожиданий по грейду. Запланирован мягкий отказ.",
    traits: {
      positive: summary.topSkills.map((s) => `Подтверждённое владение — ${s}`),
      negative: [summary.mainRisk],
    },
    rejection_timer_days: summary.status === "pending_rejection" ? 14 : null,
    rejection_message_template:
      summary.status === "pending_rejection"
        ? "Спасибо за отклик. К сожалению, вы не прошли первичный скрининг в этот раз."
        : null,
    topSkills: summary.topSkills,
    mainRisk: summary.mainRisk,
    strengths: summary.topSkills.slice(0, 2).map((s) => `Уверенно работает с ${s}`),
    risks: [summary.mainRisk, "Глубина владения уточняется на интервью"],
    skillChecklist: summary.topSkills.map((s) => ({
      name: s,
      evidence: "partial" as const,
    })),
    interviewQuestions: [
      "Расскажите про самый значимый проект на текущем месте.",
      `Подробнее про ваш опыт с ${summary.topSkills[0] ?? "вашим основным стеком"}.`,
      "Как вы балансируете между скоростью и качеством?",
    ],
    scoreBreakdown: [
      { label: "Релевантный опыт", weight: 30, signal: "Соответствие профилю роли" },
      { label: "Решение задач", weight: 25, signal: "Аргументация в ответах чата" },
      { label: "Покрытие стека", weight: 20, signal: "Заявленные навыки vs профиль роли" },
      { label: "Коммуникация", weight: 15, signal: "Ясность и структура ответов" },
      { label: "Ownership", weight: 10, signal: "Готовность брать ответственность" },
    ],
  };
}
